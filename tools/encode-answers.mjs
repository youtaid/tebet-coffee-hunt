const KEY = 'tebet-coffee-vault';

const PLAIN = {
  'm1.q1.t': '18',
  'm1.digit.A': '1',
  'm2.q1.xyz': '512',
  'm2.digit.B': '8',
  'm3.q1.a': '6',
  'm3.q1.b': '11',
  'm3.q2.s': '35',
  'm3.q3.x': '7',
  'm3.digit.C': '7',
  'm4.q1.sum': '112',
  'm4.q2.xy': '50',
  'm4.q3.x': '25',
  'm4.q3.y': '25',
  'm4.digit.D': '0',
  'vault.pin': '1870',
};

function enc(s) {
  const bytes = [...s].map((ch, i) => ch.charCodeAt(0) ^ KEY.charCodeAt(i % KEY.length));
  return Buffer.from(bytes).toString('base64');
}

const out = Object.fromEntries(Object.entries(PLAIN).map(([k, v]) => [enc(k), enc(v)]));
